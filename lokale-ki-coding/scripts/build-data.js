"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { readData } = require("./validate-data.js");

try {
  const data = readData();
  const output = "// Generated by scripts/build-data.js. Edit models.json instead.\nwindow.LocalCodingModels = " + JSON.stringify(data, null, 2) + ";\n";
  fs.writeFileSync(path.resolve(__dirname, "../data/models.js"), output);
  console.log("Datenprüfung und Build erfolgreich: " + data.models.length + " Modelle.");
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
